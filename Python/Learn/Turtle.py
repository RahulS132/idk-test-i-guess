import turtle

# Create a Turtle object that can draw by moving around the screen.
qazi_turtle = turtle.Turtle()


# Square
# This function repeats four moves to draw a square.
def square():
    qazi_turtle.forward(100)
    qazi_turtle.right(90)
    qazi_turtle.forward(100)
    qazi_turtle.right(90)
    qazi_turtle.forward(100)
    qazi_turtle.right(90)
    qazi_turtle.forward(100)


square()

qazi_turtle.forward(100)
square()
