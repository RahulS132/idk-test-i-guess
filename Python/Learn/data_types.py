# A string is text written inside quotes.
name = "Rahul"
print(name, type(name))
# An integer is a whole number with no decimal part.
age = 18
print(age, type(age))
# A float is a number that can contain a decimal part.
height = 5.10
print("Your Height is:", height, "Type of Value=", type(height))
# Multiple variables can be assigned at the same time.
# A boolean stores either True or False.
a, b, c, d = 10, 69.69, 'Python', True
print("a=", a, "Type=", type(a))
print("b=", b, "Type=", type(b))
print("c=", c, "Type=", type(c))
print("d=", d, "Type=", type(d))
# Mutable objects can be changed after creation, such as lists and dictionaries.
# Immutable objects cannot be changed after creation, such as integers and strings.
